def _extract_json_object(text: str) -> dict[str, Any] | None:
    """Parse the first complete JSON object out of a model response."""
    if not isinstance(text, str) or not text.strip():
        return None
    candidate = _JSON_FENCE_RE.sub("", text.strip()).strip()
    for attempt in (candidate, text.strip()):
        try:
            parsed = json.loads(attempt)
        except (json.JSONDecodeError, ValueError):
            parsed = None
        if isinstance(parsed, dict):
            return parsed
    # Balanced-brace scan: tolerates prose before/after the payload.
    start = candidate.find("{")
    while start != -1:
        depth = 0
        in_string = False
        escaped = False
        for index in range(start, len(candidate)):
            char = candidate[index]
            if in_string:
                if escaped:
                    escaped = False
                elif char == "\\":
                    escaped = True
                elif char == '"':
                    in_string = False
                continue
            if char == '"':
                in_string = True
            elif char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    try:
                        parsed = json.loads(candidate[start : index + 1])
                    except (json.JSONDecodeError, ValueError):
                        parsed = None
                    if isinstance(parsed, dict):
                        return parsed
                    break
        start = candidate.find("{", start + 1)
    return None


def _text_field(payload: dict[str, Any], key: str, *, limit: int) -> str:
    """Read a bounded string field, tolerating absent or non-string values."""
    value = payload.get(key)
    if not isinstance(value, str):
        return ""
    text = value.strip()
    if len(text) > limit:
        text = text[:limit].rstrip()
    return text


def _section(text: str) -> str:
    """Normalize a model-provided markdown section.

    Three defenses, because this text becomes part of a published SKILL.md:

    - strips leading YAML frontmatter delimiters so model output can never forge
      a second frontmatter block;
    - drops a leading ATX heading, because the template already emits the
      section heading and models routinely repeat it (a doubled
      ``## 适用场景`` otherwise ships in every generated skill). Deeper
      sub-headings inside the body are preserved;
    - normalizes CRLF to LF to match the bytes skill storage publishes.
    """
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.split("\n")
    while lines and lines[0].strip() in {"---", ""}:
        lines.pop(0)
    if lines and lines[0].lstrip().startswith("#"):
        lines.pop(0)
        while lines and not lines[0].strip():
            lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines).strip()


def _yaml_scalar(value: object) -> str:
    """Emit a YAML-safe double-quoted scalar.

    YAML is a superset of JSON for scalars, so a JSON-encoded string is always a
    valid YAML double-quoted scalar — this keeps colons, quotes, hashes and
    newlines in model-provided text from breaking the frontmatter.
    """
    return json.dumps("" if value is None else str(value), ensure_ascii=False)


def _lf(text: str) -> str:
    """Normalize line endings so the published document is uniformly LF.

    Skill storage publishes byte-faithfully and the scanner reads those exact
    bytes, so a CRLF carried in from model output would diverge from the rest of
    the document.
    """
    return text.replace("\r\n", "\n").replace("\r", "\n")


def render_skill_markdown(
    *,
    name: str,
    scenario: str,
    description: str,
    when_to_use: str,
    data_fetching: str,
    reasoning: str,
    answer_format: str,
    caveats: str,
    version: int,
    thread_id: str | None,
    run_id: str | None,
    examples: str = "",
) -> str:
    """Render the ``SKILL.md`` document for a generated skill."""
    scenario = _lf(scenario).strip()
    description = _lf(description).strip()
    when_to_use = _lf(when_to_use).strip()
    data_fetching = _lf(data_fetching).strip()
    reasoning = _lf(reasoning).strip()
    answer_format = _lf(answer_format).strip()
    caveats = _lf(caveats).strip()
    examples = _lf(examples).strip()

    generated_at = datetime.now(UTC).isoformat(timespec="seconds")
    frontmatter_lines = [
        "---",
        f"name: {name}",
        f"description: {_yaml_scalar(description)}",
        "metadata:",
        f"  author: {_yaml_scalar(AUTO_SKILL_AUTHOR)}",
        f"  version: {_yaml_scalar(version)}",
        f"  scenario: {_yaml_scalar(scenario)}",
        f"  generated-at: {_yaml_scalar(generated_at)}",
    ]
    if thread_id:
        frontmatter_lines.append(f"  source-thread: {_yaml_scalar(thread_id)}")
    if run_id:
        frontmatter_lines.append(f"  source-run: {_yaml_scalar(run_id)}")
    frontmatter_lines.append("---")

    title = scenario or name
    body_sections = [
        f"# {title}",
        "",
        f"> 本技能由 DeerFlow auto-skill 从真实运行轨迹自动沉淀生成（当前版本 v{version}，历史版本存于备份库）。",
        "> 除「示例」外，正文只描述方法与路径，不绑定任何具体主体：换一个公司、一个报告期或一个地区同样适用。",
        "",
        "## 适用场景",
        "",
        when_to_use or description or "参见 description。",
        "",
        "## 取数逻辑",
        "",
        data_fetching or "（本次运行未产生可复用的取数步骤）",
        "",
        "## 推理逻辑",
        "",
        reasoning or "（本次运行未产生可复用的推理步骤）",
        "",
        "## 回答格式",
        "",
        answer_format or "按用户请求的自然结构组织回答。",
    ]
    if examples:
        body_sections.extend(["", "## 示例", "", examples])
    if caveats:
        body_sections.extend(["", "## 注意事项", "", caveats])

    return "\n".join(frontmatter_lines) + "\n\n" + "\n".join(body_sections) + "\n"


def resolve_matched_auto_skills(trajectory: RunTrajectory) -> list[store.StoredSkill]:
    """Return the globally stored auto-skills this run actually loaded.

    Only packages that still exist in the global store count: a name from
    ``skill_context`` may refer to a legacy per-user package or to one that has
    since been retired, and echoing stale content into the prompt would make the
    model "improve" something that is no longer there.
    """
    matched: list[store.StoredSkill] = []
    seen: set[str] = set()
    for name in trajectory.skill_names:
        if name in seen:
            continue
        seen.add(name)
        stored = store.read_current(name)
        if stored is not None:
            matched.append(stored)
    return matched


def _render_existing_skills_section(matched: list[store.StoredSkill]) -> str:
    """Bound and format the existing skills for the synthesis prompt."""
    if not matched:
        return "## 当前已有技能\n（无：本次运行未命中任何自动生成的技能）"
    blocks: list[str] = []
    for stored in matched:
        body = stored.content.strip()
        if len(body) > _EXISTING_SKILL_CHAR_BUDGET:
            body = body[:_EXISTING_SKILL_CHAR_BUDGET] + "\n…[truncated]"
        blocks.append(f"### 已有技能：{stored.name}（v{stored.version}）\n\n```markdown\n{body}\n```")
    return "## 当前已有技能\n\n" + "\n\n".join(blocks)


def _render_scenario_index() -> str:
    """List every existing global auto-skill so the model can reuse a scenario.

    Without this, a run that never loaded its scenario's skill (``skill_context``
    empty, which is common — the model often goes straight to the tools) would
    leave the synthesizer unaware that the scenario already exists, and it would
    mint a near-duplicate package under a different slug. Showing names plus
    descriptions lets the model either reuse the existing ``scenario_slug`` — which
    resolves to the same stable name and therefore an update — or answer
    ``no_change``.
    """
    try:
        summaries = store.list_current_summaries()
    except Exception:
        logger.warning("auto-skill could not list existing scenarios; continuing without the index", exc_info=True)
        return ""
    if not summaries:
        return ""

    lines = ["## 平台已有的自动技能清单（用于避免重复建场景）"]
    for name, version, description in summaries[:_INDEX_MAX_ENTRIES]:
        clipped = description.strip().replace("\n", " ")
        if len(clipped) > _INDEX_DESCRIPTION_BUDGET:
            clipped = clipped[:_INDEX_DESCRIPTION_BUDGET] + "…"
        lines.append(f"- `{name}`（v{version}）：{clipped or '（无描述）'}")
    if len(summaries) > _INDEX_MAX_ENTRIES:
        lines.append(f"- …另有 {len(summaries) - _INDEX_MAX_ENTRIES} 个未列出")
    lines.append("")
    lines.append("判定纪律：如果本次运行属于上表某个已存在的场景，必须复用该技能名对应的 scenario_slug（即去掉 auto- 前缀的部分），并在 decision 中给出 update 或 no_change；不要为同一场景另起一个新 slug。")
    return "\n".join(lines)


def _field_text(payload: dict[str, Any], field: str) -> str:
    """Read one publishable field at the same bound the renderer applies."""
    return _text_field(payload, field, limit=_FIELD_LIMITS.get(field, _SECTION_CHAR_BUDGET))


def _abstract_surfaces(payload: dict[str, Any]) -> dict[str, str]:
    """The fields that must stay abstract, at their published bounds."""
    return {field: _field_text(payload, field) for field in _ABSTRACT_FIELDS}


def _leaked_entities(payload: dict[str, Any], entities: tuple[str, ...]) -> dict[str, tuple[str, ...]]:
    """Map each abstract field to the concrete entities it contains."""
    if not entities:
        return {}
    return leaked_fields(_abstract_surfaces(payload), entities)


def _adopt_repaired_fields(payload: dict[str, Any], repaired: dict[str, Any]) -> dict[str, Any]:
    """Take the repair attempt's content fields, keeping the original decision.

    The repair call's only job is abstraction, so ``decision`` / ``reason`` /
    ``scenario_slug`` stay as first resolved: adopting a second opinion there
    could rename the package mid-flight. A field the model omitted is kept from
    the original rather than blanked.
    """
    merged = dict(payload)
    for field in (*_ABSTRACT_FIELDS, "examples"):
        value = repaired.get(field)
        if isinstance(value, str) and value.strip():
            merged[field] = value
    entities = repaired.get("entities")
    if isinstance(entities, (list, tuple, str)):
        merged["entities"] = entities
    return merged


def _redact_payload(payload: dict[str, Any], entities: tuple[str, ...]) -> dict[str, Any]:
    """Deterministically remove the leaked entities from the abstract fields."""
    merged = dict(payload)
    merged.update(redact_surfaces(_abstract_surfaces(payload), entities))
    return merged


def _render_tool_diff_section(trajectory: RunTrajectory, matched: list[store.StoredSkill]) -> str:
    """State the platform's own tool diff, so an unevidenced ``new_tool`` is visible.

    The model is asked to claim ``new_tool`` only when the run went outside the
    skill's definition; handing it the same join the verifier computes keeps the
    claim and the check agreeing, and gives the ``no_change`` discipline a fact to
    lean on instead of an impression.
    """
    if not matched:
        return ""
    tool_names = list(dict.fromkeys(step.tool_name for step in trajectory.tool_steps))
    if not tool_names:
        return ""
    novel = find_novel_tools(tool_names, [stored.content for stored in matched])
    lines = [
        "## 平台确定性核对：工具差异",
        f"- 本次运行调用的工具：{', '.join(f'`{name}`' for name in tool_names[:_TOOL_DIFF_MAX_TOOLS])}",
    ]
    if novel:
        lines.append(f"- 其中已有技能正文**未提及**的工具：{', '.join(f'`{name}`' for name in novel)}")
    else:
        lines.append("- 已有技能正文已覆盖本次调用的全部工具，本次没有新工具。")
    lines.extend(["", "update_reasons 中的 new_tool 必须与上面的核对一致；不一致时该理由会被平台丢弃。"])
    return "\n".join(lines)


async def _repair_abstraction(
    *,
    payload: dict[str, Any],
    leaks: dict[str, tuple[str, ...]],
    evidence: str,
    config: AutoSkillConfig,
    app_config: AppConfig,
    thread_id: str | None,
) -> dict[str, Any]:
    """Give the model one chance to abstract its own output.

    Returns the merged payload. A failed, unparseable or raising repair keeps the
    original so the caller's deterministic redaction still runs: the abstraction
    invariant holds either way, and a repair outage must not discard the trajectory.
    """
    leaked = sorted({entity for found in leaks.values() for entity in found})[:_REPAIR_ENTITY_BUDGET]
    instruction = _SYNTHESIS_SYSTEM_INSTRUCTION + _ABSTRACTION_REPAIR_INSTRUCTION.format(entities="、".join(f"“{entity}”" for entity in leaked))
    try:
        raw = await run_oneshot_llm(
            system_instruction=instruction,
            user_content=evidence,
            run_name=AUTO_SKILL_RUN_NAME,
            app_config=app_config,
            model_name=config.model_name,
            thread_id=thread_id,
        )
    except Exception:
        logger.warning("auto-skill abstraction repair failed; redacting instead (thread=%s)", thread_id, exc_info=True)
        return payload
    repaired = _extract_json_object(raw)
    if not isinstance(repaired, dict):
        logger.warning("auto-skill abstraction repair returned no JSON object; redacting instead (thread=%s)", thread_id)
        return payload
    return _adopt_repaired_fields(payload, repaired)


async def _static_scan_or_raise(name: str, content: str) -> list[dict[str, Any]]:
    """Run the deterministic scanner over the exact bytes about to be published."""

    def _scan() -> list[Any]:
        with tempfile.TemporaryDirectory() as tmp:
            skill_dir = Path(tmp) / name
            skill_dir.mkdir(parents=True)
            target = skill_dir / SKILL_MD_FILE
            target.write_text(content, encoding="utf-8", newline="")
            return enforce_static_scan(skill_dir, skill_name=name)

    return list(await asyncio.to_thread(_scan))


async def _moderation_scan_or_raise(content: str, *, name: str, static_findings: list[Any]) -> str:
    """Run the LLM moderation scan, raising on a block decision."""
    result = await scan_skill_content(
        content,
        executable=False,
        location=f"{store.PROVIDER_DIR_NAME}/{name}/{SKILL_MD_FILE}",
        static_findings=list(static_findings),
        # Standalone background caller outside the graph, so tracing belongs here.
        attach_tracing=True,
    )
    if result.decision == "block":
        raise AutoSkillSynthesisError(f"security scan blocked the generated skill: {result.reason}")
    return str(result.decision)


async def _invalidate_caches_globally(name: str) -> None:
    """Retire the prompt-layer skill caches in this process and every peer.

    The package is global, so the reset is published **without** a ``user_id``:
    a user-scoped marker would leave other users' per-config cache entries
    serving a skill list that no longer matches disk.
    """
    await refresh_skills_system_prompt_cache_async()
    try:
        await asyncio.to_thread(publish_skills_cache_reset)
    except SkillCacheResetPublishError:
        # The write is durable; only cross-process notification failed.
        logger.error("auto-skill %s was published, but the shared skills cache reset could not be published", name, exc_info=True)


async def synthesize_skill(
    *,
    trajectory: RunTrajectory,
    user_id: str,
    thread_id: str | None,
    run_id: str | None,
    config: AutoSkillConfig,
    app_config: AppConfig,
) -> SynthesizedSkill | None:
    """Synthesize and publish one skill from a run trajectory.

    Returns the published skill, or ``None`` when synthesis was skipped, judged
    unnecessary (``no_change``), rejected or failed. Never raises: this runs on a
    background worker whose failure must not surface anywhere a user can see.
    """
    try:
        matched = resolve_matched_auto_skills(trajectory)
        evidence = "\n\n".join(
            part
            for part in (
                render_trajectory(trajectory, max_chars=config.max_trajectory_chars),
                _render_existing_skills_section(matched),
                _render_tool_diff_section(trajectory, matched),
                _render_scenario_index(),
            )
            if part
        )
        raw = await run_oneshot_llm(
            system_instruction=_SYNTHESIS_SYSTEM_INSTRUCTION,
            user_content=evidence,
            run_name=AUTO_SKILL_RUN_NAME,
            app_config=app_config,
            model_name=config.model_name,
            thread_id=thread_id,
        )
        payload = _extract_json_object(raw)
        if payload is None:
            # One retry: a reasoning model occasionally answers in prose or emits
            # a truncated object. Background work can afford a second attempt, and
            # a bounded raw snippet is the only way to diagnose this in production.
            logger.warning(
                "auto-skill synthesis returned no JSON object; retrying once (thread=%s run=%s) raw_head=%r",
                thread_id,
                run_id,
                (raw or "")[:_RAW_DIAGNOSTIC_BUDGET],
            )
            raw = await run_oneshot_llm(
                system_instruction=_SYNTHESIS_SYSTEM_INSTRUCTION + "\n\n【重要】上一次输出无法解析。本次必须只输出一个合法 JSON 对象，不要任何前后说明文字，不要 markdown 代码块。",
                user_content=evidence,
                run_name=AUTO_SKILL_RUN_NAME,
                app_config=app_config,
                model_name=config.model_name,
                thread_id=thread_id,
            )
            payload = _extract_json_object(raw)
        if payload is None:
            logger.warning(
                "auto-skill synthesis returned no JSON object after retry; skipping (thread=%s run=%s) raw_head=%r",
                thread_id,
                run_id,
                (raw or "")[:_RAW_DIAGNOSTIC_BUDGET],
            )
            return None

        decision = _text_field(payload, "decision", limit=32).lower() or "create"
        if decision not in _VALID_DECISIONS:
            logger.warning("auto-skill synthesis returned unknown decision %r; treating as create", decision)
            decision = "create"
        reason = _text_field(payload, "reason", limit=400)

        if decision == "no_change":
            logger.info("auto-skill no_change for thread=%s run=%s: %s", thread_id, run_id, reason or "(no reason given)")
            return None

        slug = scenario_slug(payload.get("scenario_slug"), query=trajectory.query)
        name = resolve_skill_name(prefix=config.name_prefix, slug=slug)
        existing_target = await asyncio.to_thread(store.read_current, name)

        # Reconcile the declared decision with what is actually on disk: a model
        # that says "create" for a scenario which already exists is still an
        # update, and the store will back the outgoing version up either way.
        # Reporting it as create would misdescribe the audit trail.
        reconciled_create = False
        if decision == "create" and existing_target is not None and existing_target.version >= 1:
            logger.info("auto-skill decision 'create' for %s which already exists; treating as update", name)
            decision = "update"
            reconciled_create = True

        # ── Verify the update claim against the run's own evidence ────────────
        # An update rewrites a package every user shares, so it needs a substantive
        # reason; a run that only differs in subject/values/wording is a no_change.
        update_reasons: tuple[str, ...] = ()
        if decision == "update":
            matched_names = {stored.name for stored in matched}
            contents = [stored.content for stored in matched]
            if existing_target is not None and existing_target.name not in matched_names:
                contents.append(existing_target.content)
            novel_tools = find_novel_tools((step.tool_name for step in trajectory.tool_steps), contents)
            verified = verify_update(
                normalize_reasons(payload.get("update_reasons")),
                novel_tools=novel_tools,
                strict=not reconciled_create,
            )
            if not verified.is_update:
                logger.info(
                    "auto-skill update downgraded to no_change for %s (thread=%s run=%s): %s",
                    name,
                    thread_id,
                    run_id,
                    verified.note or "no substantive reason",
                )
                return None
            update_reasons = verified.reasons
            if verified.dropped:
                logger.info("auto-skill %s dropped update reason(s): %s", name, ", ".join(verified.dropped))

        # ── Abstraction gate: concrete entities belong to the examples only ───
        entities = collect_entities(payload.get("entities"))
        leaks = _leaked_entities(payload, entities)
        redacted_entities: tuple[str, ...] = ()
        if leaks:
            payload = await _repair_abstraction(
                payload=payload,
                leaks=leaks,
                evidence=evidence,
                config=config,
                app_config=app_config,
                thread_id=thread_id,
            )
            entities = collect_entities(payload.get("entities"))
            leaks = _leaked_entities(payload, entities)
            if leaks:
                redacted_entities = tuple(sorted({entity for found in leaks.values() for entity in found}))
                payload = _redact_payload(payload, entities)
                logger.warning(
                    "auto-skill %s redacted concrete entities from %s (thread=%s run=%s)",
                    name,
                    ", ".join(sorted(leaks)),
                    thread_id,
                    run_id,
                )
            else:
                logger.info("auto-skill %s abstraction repair removed the concrete entities (thread=%s run=%s)", name, thread_id, run_id)

        scenario = _field_text(payload, "scenario") or "auto scenario"
        description = _field_text(payload, "description")
        if not description:
            logger.warning("auto-skill synthesis produced no description; skipping (thread=%s run=%s)", thread_id, run_id)
            return None

        def _render(version: int) -> str:
            return render_skill_markdown(
                name=name,
                scenario=scenario,
                description=description,
                when_to_use=_section(_field_text(payload, "when_to_use")),
                data_fetching=_section(_field_text(payload, "data_fetching")),
                reasoning=_section(_field_text(payload, "reasoning")),
                answer_format=_section(_field_text(payload, "answer_format")),
                caveats=_section(_field_text(payload, "caveats")),
                examples=_section(_field_text(payload, "examples")),
                version=version,
                thread_id=thread_id,
                run_id=run_id,
            )

        # Security-scan the bytes we expect to publish. The version digit is
        # assigned inside the store's lock, so a concurrent writer can make the
        # published content differ from this candidate by that one field; the
        # scanned body is identical either way.
        expected_version = (existing_target.version if existing_target is not None else 0) + 1
        candidate = _render(expected_version)
        try:
            static_findings = await _static_scan_or_raise(name, candidate)
        except StaticScanBlockedError as exc:
            logger.warning("auto-skill static scan blocked %s: %s", name, exc)
            return None
        except StaticScannerError as exc:
            logger.warning("auto-skill static scan failed for %s: %s", name, exc)
            return None

        scanner_decision = await _moderation_scan_or_raise(candidate, name=name, static_findings=static_findings)

        result = await asyncio.to_thread(store.write_skill, name, render=_render, prune_keep=config.max_versions)

        # A global package changed: retire caches in this process and every peer.
        await await_drained(_invalidate_caches_globally(name))

        swept: tuple[str, ...] = ()
        try:
            swept = tuple(await asyncio.to_thread(store.sweep_legacy_user_skills, user_id, prefix=config.name_prefix, slug=slug))
            if swept:
                await await_drained(_invalidate_caches_globally(name))
        except Exception:
            # Migration is housekeeping: a failure must not undo the publication.
            logger.warning("auto-skill legacy sweep failed for user=%s scenario=%s", user_id, slug, exc_info=True)

        logger.info(
            "auto-skill %s %s v%d (scenario=%s, backed_up=%s, scanner=%s, reasons=%s, redacted=%s)",
            decision,
            name,
            result.version,
            scenario,
            result.backed_up_version,
            scanner_decision,
            ",".join(update_reasons) or "-",
            ",".join(redacted_entities) or "-",
        )
        return SynthesizedSkill(
            name=name,
            version=result.version,
            scenario=scenario,
            description=description,
            content=result.content,
            scanner_decision=scanner_decision,
            decision=decision,
            backed_up_version=result.backed_up_version,
            pruned=result.pruned,
            swept=swept,
            update_reasons=update_reasons,
            redacted_entities=redacted_entities,
        )
    except AutoSkillSynthesisError as exc:
        logger.warning("auto-skill synthesis rejected: %s", exc)
        return None
    except Exception:
        logger.warning("auto-skill synthesis failed; skipping (thread=%s run=%s)", thread_id, run_id, exc_info=True)
        return None
