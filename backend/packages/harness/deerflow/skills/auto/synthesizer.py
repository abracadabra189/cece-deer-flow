"""Turn one run trajectory into a globally shared, version-managed skill.

Two decisions shape this module.

**Global, not per-user.** The package is published through
:mod:`deerflow.skills.auto.store` into the global integrations root, so a skill
learned from one user's run is matchable by every other user. See that module's
docstring for why the integrations root is the only location that satisfies
"shared + writable at runtime + enabled by default for everyone".

**Update, don't accumulate.** When the run actually used an existing auto-skill,
its current content is handed to the model alongside the trajectory and the model
returns an explicit ``decision``:

- ``no_change`` — the skill already covers this run; nothing is written, so
  repeatedly running a solved scenario does not churn versions or spend tokens;
- ``update`` — the run revealed something the skill lacks (a tool it did not
  mention, a better parameter, a failure fallback, a sharper answer format); the
  improved package replaces the visible one and the outgoing version moves to the
  backup store;
- ``create`` — no existing skill covers the scenario.

Because the visible name is stable, "users only see the latest version" holds by
construction: there is exactly one discoverable package per scenario, and every
superseded version stays restorable from the backup store.

Security is unchanged from the agent-driven path: generated bytes pass
``validate_skill_name``, ``validate_skill_markdown_content``-equivalent parsing,
the deterministic SkillScan and the LLM moderation scan — the same gates
``skill_manage`` applies — before anything is published. Everything is best
effort: a model failure, a rejected scan or a write error is logged and dropped,
never raised into a run.
"""

